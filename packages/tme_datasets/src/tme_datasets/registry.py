def query_preprocessed_datasets(
    dataset_ids: Sequence[str] | None = None,
    *,
    modality: Modality | str | None = None,
    cancer_type: str | None = None,
    has_response: bool | None = None,
    exclude_dysfunctional: bool = True,
    as_polars: bool = False,
    repo_root: Path | None = None,
) -> PreprocessedDatasets | pl.DataFrame:
    """Query available on-disk preprocessed datasets with optional filtering and Polars DataFrame conversion.

    Args:
        dataset_ids: Optional sequence of dataset IDs or aliases to include.
        modality: Optional modality filter (e.g. Modality.SINGLE_CELL, "single_cell", "bulk").
        cancer_type: Optional cancer type filter (case-insensitive).
        has_response: Optional filter for response label availability.
        exclude_dysfunctional: If True, exclude cohorts flagged as dysfunctional. Defaults to True.
        as_polars: If True, returns a strongly typed Polars DataFrame. Defaults to False.
        repo_root: Optional repository root path override.

    Returns:
        PreprocessedDatasets or pl.DataFrame: The matching preprocessed datasets.
    """
    preprocessed = list_preprocessed_datasets(
        modality=modality,
        cancer_type=cancer_type,
        has_response=has_response,
        exclude_dysfunctional=exclude_dysfunctional,
        repo_root=repo_root,
    )

    if dataset_ids is not None:
        target_canonical_ids = {resolve_dataset_id(did) for did in dataset_ids}
        filtered_specs = [s for s in preprocessed if s.id in target_canonical_ids]
        preprocessed = PreprocessedDatasets(filtered_specs)

    if as_polars:
        return preprocessed.to_polars()
    return preprocessed


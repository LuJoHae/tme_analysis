def resolve_dataset_id(dataset_id: str) -> str:
    """Resolve an alias or study name to its canonical primary dataset ID."""
    return DATASET_ALIASES.get(dataset_id, dataset_id)


def get_dataset_spec(dataset_id: str) -> Maybe[DatasetSpec]:
    """Retrieve the immutable dataset metadata specification by ID or alias."""
    canonical_id = resolve_dataset_id(dataset_id)
    return Some(DATASET_REGISTRY[canonical_id]) if canonical_id in DATASET_REGISTRY else Nothing


def list_registered_datasets() -> RegisteredDatasets:
    """Return an enriched collection of all registered dataset specifications."""
    return RegisteredDatasets(DATASET_REGISTRY.values())


def list_preprocessed_datasets(
    modality: Modality | str | None = None,
    cancer_type: str | None = None,
    has_response: bool | None = None,
    exclude_dysfunctional: bool = True,
    repo_root: Path | None = None,
) -> PreprocessedDatasets:
    """Return an immutable collection of registered datasets available as preprocessed H5AD files.

    Scans the dataset registry and candidate storage paths (including data/preprocessed,
    configured overrides, and cluster storage) for existing, non-empty H5AD files.

    Args:
        modality: Optional modality filter (e.g. Modality.SINGLE_CELL, "single_cell", "bulk").
        cancer_type: Optional cancer type filter (case-insensitive).
        has_response: Optional filter for response label availability.
        exclude_dysfunctional: If True, exclude cohorts flagged as dysfunctional. Defaults to True.
        repo_root: Optional repository root path override.

    Returns:
        PreprocessedDatasets: Immutable tuple container of PreprocessedDatasetSpec models.
    """
    from .paths import find_dataset_h5ad, get_data_paths

    specs: list[PreprocessedDatasetSpec] = []
    seen_ids: set[str] = set()

    # 1. Scan registered datasets using candidate path resolver (find_dataset_h5ad)
    for ds_id, reg_spec in DATASET_REGISTRY.items():
        if ds_id in seen_ids:
            continue
        h5ad_maybe = find_dataset_h5ad(ds_id, repo_root=repo_root)
        match h5ad_maybe:
            case Some(h5ad_path):
                seen_ids.add(ds_id)
                size_mb = round(h5ad_path.stat().st_size / (1024.0 * 1024.0), 2)
                prep_spec = PreprocessedDatasetSpec(
                    id=reg_spec.id,
                    title=reg_spec.title,
                    modality=reg_spec.modality,
                    cancer_type=reg_spec.cancer_type,
                    platform=reg_spec.platform,
                    organ=reg_spec.organ,
                    has_response_labels=reg_spec.has_response_labels,
                    n_samples_or_cells=reg_spec.n_samples_or_cells,
                    h5ad_path=h5ad_path,
                    file_size_mb=size_mb,
                    has_qc_spec=isinstance(reg_spec.qc_spec, Some),
                    is_dysfunctional=reg_spec.is_dysfunctional,
                )
                specs.append(prep_spec)
            case _:
                continue

    # 2. Also check if there are additional .h5ad files in preprocessed_dir matching aliases
    cfg = get_data_paths(repo_root=repo_root)
    if cfg.preprocessed_dir.exists():
        for file_path in cfg.preprocessed_dir.glob("*.h5ad"):
            if not file_path.is_file() or file_path.stat().st_size == 0:
                continue
            canonical_id = resolve_dataset_id(file_path.stem)
            if canonical_id in DATASET_REGISTRY and canonical_id not in seen_ids:
                reg_spec = DATASET_REGISTRY[canonical_id]
                seen_ids.add(canonical_id)
                size_mb = round(file_path.stat().st_size / (1024.0 * 1024.0), 2)
                prep_spec = PreprocessedDatasetSpec(
                    id=reg_spec.id,
                    title=reg_spec.title,
                    modality=reg_spec.modality,
                    cancer_type=reg_spec.cancer_type,
                    platform=reg_spec.platform,
                    organ=reg_spec.organ,
                    has_response_labels=reg_spec.has_response_labels,
                    n_samples_or_cells=reg_spec.n_samples_or_cells,
                    h5ad_path=file_path,
                    file_size_mb=size_mb,
                    has_qc_spec=isinstance(reg_spec.qc_spec, Some),
                    is_dysfunctional=reg_spec.is_dysfunctional,
                )
                specs.append(prep_spec)

    result = PreprocessedDatasets(specs)
    return result.filter(
        modality=modality,
        cancer_type=cancer_type,
        has_response=has_response,
        exclude_dysfunctional=exclude_dysfunctional,
    )


